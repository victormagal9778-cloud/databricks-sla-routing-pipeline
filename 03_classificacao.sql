 keys_joined AS (
   SELECT k.CRM_TRIM, k.CRM_PAD9, kw.PROCESSO_FMT, kw.IDWORKFLOW, kw.IS_ABERTO
   FROM keys_norm_ov k JOIN keys_wf_ov kw ON kw.WF_TRIM = k.CRM_TRIM
   UNION
   SELECT k.CRM_TRIM, k.CRM_PAD9, kw.PROCESSO_FMT, kw.IDWORKFLOW, kw.IS_ABERTO
   FROM keys_norm_ov k JOIN keys_wf_ov kw ON kw.WF_PAD9 = k.CRM_PAD9
