 -- [3] keys_joined: OR-JOIN resolvido via UNION
 --     O padrão ON (WF_TRIM = CRM_TRIM OR WF_PAD9 = CRM_PAD9)
 --     impedia hash join no Spark e aparecia duas vezes
 --     (wf_hist_aggr + wf_hist_ids). Ambas as CTEs consomem
